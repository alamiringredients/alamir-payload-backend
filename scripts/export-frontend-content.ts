import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { formPolicies } from '../src/services/formPolicy'
import { pageDefinitions } from '../src/blocks/pageDefinitions'
import { recordDefinitions } from '../src/blocks/recordSections'

const owners = Object.fromEntries(
  Object.entries(formPolicies)
    .filter(([, policy]) => policy.page)
    .map(([purpose, { page, collection }]) => [
      purpose,
      { page, collection: collection ?? 'pages' },
    ]),
)
const sections = pageDefinitions.flatMap((page) =>
  page.sections.map((section) => ({
    slug: `${page.slug}-${section.name}`,
    pageKey: page.key,
    pageSlug: page.slug,
    name: section.name,
    sourceName: page.slug === 'news' ? 'copy' : section.name,
    label: section.label,
  })),
)
const records = recordDefinitions.flatMap(({ collection, sections }) =>
  sections.map((section) => ({
    slug: section.slug,
    collection,
    name: section.name,
    page: section.pageFields.flatMap((field) => ('name' in field ? [field.name] : [])),
    root: Object.fromEntries(
      section.contentFields.flatMap((field) =>
        'name' in field
          ? [
              [
                field.name === 'bodyCopy' && collection === 'events' ? 'body' : field.name,
                field.type,
              ],
            ]
          : [],
      ),
    ),
  })),
)
const artifacts = {
  'forms/owner-policy.ts': `// Generated by the backend's npm run content:sync.\nexport const ownerFormPolicy = ${JSON.stringify(owners, null, 2)} as const;\n`,
  'payload/sections.json': `${JSON.stringify(sections)}\n`,
  'payload/record-sections.json': `${JSON.stringify(records)}\n`,
}
for (const [relative, content] of Object.entries(artifacts)) {
  const destination = fileURLToPath(
    new URL(`../../alamir-payload-frontend/lib/${relative}`, import.meta.url),
  )
  if (process.argv.includes('--check')) {
    if ((await readFile(destination, 'utf8')) !== content)
      throw new Error(
        `Frontend content contract is stale: ${relative}. Run npm run content:sync in the backend.`,
      )
  } else await writeFile(destination, content)
}
